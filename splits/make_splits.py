"""Generate the shared train/validation/test split JSON for each dataset.

Layout (v1): six chunks, three validation and three test, centred at 15, 29, 43, 57, 71 and 85% of the
run in the order V T T V V T. Each chunk has GAP excluded dumps on both sides. Validation and test
are each 15% of the non-excluded dumps; train is everything else.

Usage (from the repo root):  .venv/bin/python splits/make_splits.py
Refuses to overwrite an existing split file; a changed split must get a new version.
"""
import hashlib
import json
import os
import re
import sys
from datetime import date

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
VERSION = "v1"
GAP = 10                                             # excluded dumps on each side of every chunk
CENTERS = (0.15, 0.29, 0.43, 0.57, 0.71, 0.85)       # chunk centres, fraction of the run
ORDER = ("validation", "test", "test", "validation", "validation", "test")
HELD_OUT_FRACTION = 0.15                             # each of validation and test, of non-excluded dumps

DATASETS = {
    "rc300_reduced": {
        "description": "rc300: reduced-resolution output of the H-AMR rc300 simulation, preprocessed by "
                       "Fall26/data/preprocess_rc300.py (raw source: NERSC /pscratch/sd/l/lalakos/ml_data_rc300/reduced).",
        "data_root": "/work/nvme/bgun/kfortune/rc300_reduced",
        "folders": ["", "blind"],          # dumps live in both; each ID appears exactly once
        "times_file": "splits.json",       # per-dump simulation time written by the preprocessing
        "notes": [
            "The blind/ folder is a storage location from an earlier 80/10/10 split and has no meaning here. "
            "Always use the per-dump 'files' paths below.",
            "Models trained on the earlier 80/10/10 split (train 3000-10707) have seen validation and test dumps "
            "of this split. Retrain on this split for a valid comparison.",
            "Cells with r < 6.11 are a coarse AMR level (half resolution, each value duplicated into 2x2x2 cells); "
            "geometry.npz 'resolved' is False there.",
        ],
    },
    "5000run": {
        "description": "5000run: the TRON dataset, preprocessed by fall26/preprocess_forecast_ds.py on the sachin branch "
                       "(raw source: NERSC /pscratch/sd/s/sachinv/5000run).",
        "data_root": "/work/nvme/bgun/centarsirius/5000run/processed_forecast",
        "folders": [""],                   # main folder only; blind/ is NOT used
        "times_file": None,
        "notes": [
            "Use the main-folder copy of every dump (confirmed correct by the benchmark owner, 2026-11-14). "
            "blind/dump_5000-5700 is an outdated preprocessing (utilde1 differs everywhere) and must not be used.",
            "Dumps start at t = 0, so the initial transient falls in train.",
        ],
    },
}

USAGE_RULES = [
    "Each split is a set of contiguous chunks (see 'segments'). Excluded dumps belong to no split; never use them.",
    "Every input frame AND every target frame of a sample (including every rollout step) must lie in ONE chunk "
    "of ONE split. Windows never span a gap or two chunks.",
    "Fit any normalization or preprocessing statistics on train only.",
    "Select checkpoints and hyperparameters on validation only. Use test only for final evaluation.",
    "Data are physical (unnormalized) values; models normalize internally and must return physical values.",
    "Do not edit this file. A changed split is a new version with a new filename.",
]


def dump_ids(folder):
    if not os.path.isdir(folder):
        return []
    return [int(m.group(1)) for f in os.listdir(folder) if (m := re.fullmatch(r"dump_(\d+)\.npy", f))]


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def chunk_sizes(total, k):
    return [total // k + (1 if i < total % k else 0) for i in range(k)]


def layout(ids):
    """Chronological segments [(split, chunk_name, first_index, last_index)] over positions in ids."""
    n = len(ids)
    held = int(HELD_OUT_FRACTION * (n - 2 * GAP * len(CENTERS)))
    sizes = {s: iter(chunk_sizes(held, ORDER.count(s))) for s in ("validation", "test")}
    counters = {"validation": 0, "test": 0}
    segments, cursor = [], 0
    for centre, split in zip(CENTERS, ORDER):
        size = next(sizes[split])
        start = round(centre * n - size / 2)
        if start - GAP < cursor:
            raise SystemExit("chunks overlap; change CENTERS")
        segments.append(("train", None, cursor, start - GAP - 1))
        segments.append(("excluded", None, start - GAP, start - 1))
        counters[split] += 1
        segments.append((split, f"{split}_{counters[split]}", start, start + size - 1))
        segments.append(("excluded", None, start + size, start + size + GAP - 1))
        cursor = start + size + GAP
    segments.append(("train", None, cursor, n - 1))
    train_count = 0
    out = []
    for split, name, a, b in segments:
        if split == "train":
            train_count += 1
            name = f"train_{train_count}"
        elif split == "excluded":
            name = f"excluded_{sum(1 for s in out if s[0] == 'excluded') + 1}"
        out.append((split, name, a, b))
    return out


def build(name, spec):
    root = spec["data_root"]
    where = {}
    for sub in spec["folders"]:
        for i in dump_ids(os.path.join(root, sub)):
            if i in where:
                raise SystemExit(f"{name}: dump {i} found in two folders")
            where[i] = os.path.join(sub, f"dump_{i}.npy")
    ids = sorted(where)
    missing = sorted(set(range(ids[0], ids[-1] + 1)) - set(ids))
    if missing:
        raise SystemExit(f"{name}: missing dump IDs {missing[:10]}")

    sample = np.load(os.path.join(root, where[ids[0]]), mmap_mode="r")
    stats = np.load(os.path.join(root, "channel_stats.npz"))
    geo = np.load(os.path.join(root, "geometry.npz"))

    segments, splits = [], {s: {"count": 0, "chunks": [], "files": []} for s in ("train", "validation", "test", "excluded")}
    for split, chunk, a, b in layout(ids):
        sel = ids[a:b + 1]
        segments.append({"chunk": chunk, "split": split, "first": sel[0], "last": sel[-1], "count": len(sel)})
        splits[split]["chunks"].append({"chunk": chunk, "first": sel[0], "last": sel[-1], "count": len(sel)})
        splits[split]["count"] += len(sel)
        splits[split]["files"] += [where[i] for i in sel]
    assert sum(s["count"] for s in splits.values()) == len(ids)

    return {
        "schema_version": 2,
        "dataset": name,
        "split_version": VERSION,
        "split_id": f"{name}_{VERSION}",
        "created": date.today().isoformat(),
        "description": spec["description"],
        "data_root": root,
        "geometry_file": "geometry.npz",
        "geometry_sha256": sha256(os.path.join(root, "geometry.npz")),
        "times_file": spec["times_file"],
        "array": {
            "shape": list(sample.shape),
            "dtype": str(sample.dtype),
            "axes": ["channel", "r", "theta", "phi"],
            "channels": [str(c) for c in stats["channel_names"]],
            "units": "physical (code units, unnormalized)",
        },
        "dt_dump": float(geo["dt_dump"]),
        "spin": float(geo["spin"]),
        "total_dumps": len(ids),
        "split_rule": {
            "method": "interleaved contiguous chunks: 3 validation + 3 test, separate positions, gaps excluded",
            "chunk_centres_fraction_of_run": list(CENTERS),
            "chunk_order": list(ORDER),
            "gap_dumps_each_side": GAP,
            "held_out_fraction_each": HELD_OUT_FRACTION,
            "rounding": "validation = test = floor(0.15 * (N - 120)), split as evenly as possible over 3 chunks "
                        "(earlier chunks get the extra dump); chunk start = round(centre * N - size / 2); "
                        "train = all remaining non-excluded dumps",
        },
        "usage_rules": USAGE_RULES,
        "notes": spec["notes"],
        "file_checksums": None,   # per-file SHA256 to be added by the benchmark repo's freeze step
        "segments": segments,     # the whole run in chronological order
        "splits": splits,
    }


def main():
    for name, spec in DATASETS.items():
        out = os.path.join(HERE, f"{name}_{VERSION}.json")
        if os.path.exists(out):
            print(f"exists, not overwriting: {out}", file=sys.stderr)
            continue
        manifest = build(name, spec)
        with open(out, "w") as f:
            json.dump(manifest, f, indent=1)
            f.write("\n")
        print(out)
        for s in manifest["segments"]:
            if s["split"] != "excluded":
                print(f"  {s['chunk']:13s} {s['first']:>6}-{s['last']:<6} ({s['count']})")
        print("  totals: " + ", ".join(f"{k} {v['count']}" for k, v in manifest["splits"].items()))


if __name__ == "__main__":
    main()
